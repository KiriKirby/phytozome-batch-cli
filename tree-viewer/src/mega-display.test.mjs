function leafOrder(newick) {
  const out = [];
  let token = '';
  let inQuote = false;
  let inLength = false;
  const flush = () => {
    const value = token.trim();
    token = '';
    if (value) out.push(value.replace(/^'|'$/g, '').replace(/''/g, "'"));
  };
  for (const ch of newick) {
    if (inLength) {
      if (ch === ',' || ch === ')' || ch === ';') inLength = false;
      else continue;
    }
    if (!inLength && ch === "'") {
      inQuote = !inQuote;
      token += ch;
      continue;
    }
    if (!inQuote && ch === ':') {
      flush();
      inLength = true;
      continue;
    }
    if (!inQuote && (ch === '(' || ch === ',' || ch === ')' || ch === ';')) {
      flush();
      continue;
    }
    token += ch;
  }
  return out;
}

